class Combination {
  final List<List<List<int>>> shape;
  int index = 0;
  Combination(this.shape);
  Combination rotate([int count = 1]) {
    index = (index + count) % shape.length;
    return this;
  }

  List<List<int>> get currentShape => shape[index];
}
